/*
 * Textos da PÁGINA PÚBLICA do formulário (/f/[slug]) e da prévia do editor, nos 13
 * idiomas (docs/PLANO_FORMULARIOS_ATENDIMENTO.md §5.8).
 *
 * A página é pública (visitante sem sessão): não usa o dicionário do painel nem t() —
 * o LocaleProvider nem carrega o dicionário em /f/. Idioma: ?lang= válido → idioma da
 * Região da empresa, só quando ela define idioma (languageConfigured) → pt, como o
 * agendamento público (lib/booking-strings.ts). As chaves seguem FORM_STRING_KEYS de
 * lib/forms.ts; os textos que o administrador escreve (rótulos, opções, botão,
 * mensagem final) não se traduzem.
 */

import type { FormStrings, PublicFormRegion } from "@/lib/forms";

export const FORM_LANGS = ["pt", "en", "es", "de", "fr", "it", "ja", "zh", "ar", "hi", "id", "ru", "tr"] as const;

export type FormLang = (typeof FORM_LANGS)[number];

export function isFormLang(value: unknown): value is FormLang {
  return typeof value === "string" && (FORM_LANGS as readonly string[]).includes(value);
}

/**
 * Idioma da página: `?lang=` válido (escolha explícita no link) → idioma da Região da
 * empresa, só quando ela define idioma (`languageConfigured`) → pt. A Região chega junto
 * com a configuração do formulário; até lá a tela mostra só o carregando.
 */
export function resolveFormLang(
  queryLang: string | string[] | null | undefined,
  region: Pick<PublicFormRegion, "language" | "languageConfigured"> | null | undefined
): FormLang {
  const raw = Array.isArray(queryLang) ? queryLang[0] : queryLang;
  const value = typeof raw === "string" ? raw.trim().toLowerCase() : raw;
  if (isFormLang(value)) return value;
  const regionLang = region?.languageConfigured === true ? region.language : null;
  return isFormLang(regionLang) ? regionLang : "pt";
}

/** Idiomas escritos da direita para a esquerda. */
export function isRtlLang(lang: string | null | undefined): boolean {
  return lang === "ar";
}

