/**
 * Idioma de um conjunto devolvido por `getFormStrings` (a prévia do editor passa só os
 * textos ao renderer). Conjunto montado à mão = null.
 */
export function formLangFromStrings(strings: FormStrings | null | undefined): FormLang | null {
  if (!strings) return null;
  for (const lang of FORM_LANGS) {
    if (STRINGS[lang] === strings) return lang;
  }
  return null;
}

